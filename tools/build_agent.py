"""Compile static public data and team prior into a standalone submission."""
import json
import argparse
from pathlib import Path
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--team',default='team.json')
parser.add_argument('--out',default='submission')
parser.add_argument('--core',default='agent_core.py',help='Policy source; use an alternate file for experiments')
args=parser.parse_args()
data=json.loads((root/'research/battle_data.json').read_text())
if (root/'research/enemy_sets.json').exists():
    data['enemy_sets']=json.loads((root/'research/enemy_sets.json').read_text())
team=json.loads((root/args.team).read_text())
own={''.join(c for c in p['name'].lower() if c.isalnum()):p for p in team}
out=root/args.out; out.mkdir(parents=True,exist_ok=True)
license_text=(root/'research/SHOWDOWN_LICENSE.txt').read_text()
header='# Generated by tools/build_agent.py; do not edit generated output.\n# Static battle data derived from Pokemon Showdown (MIT):\n'
header+='\n'.join('# '+line for line in license_text.splitlines())+'\n'
(out/'agent.py').write_text(header+'DATA = '+repr(data)+'\nOWN = '+repr(own)+'\n'+(root/args.core).read_text(),encoding='utf-8')
lines=[]
for p in team:
    lines += [p['name']+' @ '+p['item'],'Ability: '+p['ability'],'EVs: '+p['evs'].split('(')[-1].rstrip(')'),p['nature']+' Nature']+['- '+m for m in p['moves']]+['']
(out/'team.txt').write_text('\n'.join(lines),encoding='utf-8')
print('Built '+str(out/'agent.py')+' and team.txt')
